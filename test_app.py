"""Interface tests: run the real app headlessly with fake network and fake Gemini."""
from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

import logic as L
from translations import TEXT

APP = str(Path(__file__).parent / "app.py")

FAKE_AQ = {
    "us_aqi": 160, "pm2_5": 70.0, "pm10": 110.0, "time": "2026-11-25T15:30", "tz": "GMT+5:30",
    "hourly_time": [f"2026-11-25T{h:02d}:00" for h in range(24)] + [f"2026-11-26T{h:02d}:00" for h in range(24)],
    "hourly_aqi": [150 + h for h in range(24)] + [140 + h for h in range(24)],
    "source": L.SOURCE,
}


@pytest.fixture(autouse=True)
def offline(monkeypatch):
    """No real network or key: fake air quality, no search results, no Gemini key anywhere."""
    import streamlit as st
    st.cache_data.clear()
    # Ignore any real key in .streamlit/secrets.toml so the tests behave the same on every computer.
    monkeypatch.setattr(type(st.secrets), "get", lambda self, name, default=None: default)
    monkeypatch.setattr(L, "fetch_aqi", lambda lat, lon, timeout=10: dict(FAKE_AQ))
    monkeypatch.setattr(L, "search_places", lambda q, timeout=10: [])
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.delenv("GEMINI_MODEL", raising=False)


def run():
    at = AppTest.from_file(APP, default_timeout=30)
    at.run()
    assert not at.exception
    return at


def labels(at):
    return [m.label for m in at.metric]


def test_english_page_shows_live_numbers_and_cards():
    at = run()
    assert at.title[0].value == TEXT["en"]["title"]
    assert "US AQI" in labels(at) and "PM2.5 µg/m³" in labels(at)
    assert at.metric[0].value == "160"
    assert len(at.metric) == 6            # 3 readings + N95, purifier and CO2 cards


def test_hindi_page_uses_hindi_labels():
    at = run()
    at.sidebar.radio[0].set_value("hi").run()
    assert not at.exception
    assert at.title[0].value == TEXT["hi"]["title"]
    assert TEXT["hi"]["n95"] in labels(at)


def test_language_switch_keeps_the_persons_choices():
    at = run()
    at.sidebar.selectbox(key="sample").set_value("Mumbai family with toddlers").run()
    before = {k: at.session_state[k] for k in ("household", "mode", "mask", "km", "purifier_cadr")}
    at.sidebar.radio[0].set_value("hi").run()
    after = {k: at.session_state[k] for k in before}
    assert after == before and before["household"] == "young_children"
    at.sidebar.radio[0].set_value("en").run()
    assert {k: at.session_state[k] for k in before} == before


def test_without_a_key_the_offline_plan_is_shown():
    at = run()
    at.button[0].click().run()
    assert not at.exception
    assert any(TEXT["en"]["nokey"] in i.value for i in at.info)
    assert any("Why it helps" in m.value for m in at.markdown)
    assert not any("GEMINI_API_KEY" in c.value for c in at.caption)     # nothing about key files leaks


def test_with_a_key_the_ai_plan_is_shown(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", "test-key")
    monkeypatch.setattr(L, "generate_text", lambda prompt, key, model: "AI PLAN TEXT")
    monkeypatch.setattr(L, "plan_with_fallback",
                        lambda prompt, key, models, used, **kw: used.update(model="m", finish="STOP", skipped=[]) or "AI PLAN TEXT")
    at = run()
    at.button[0].click().run()
    assert not at.exception
    assert any("AI PLAN TEXT" in m.value for m in at.markdown)
    assert any(c.value == "Generated by m · finish: STOP" for c in at.caption)


def test_busy_gemini_falls_back_to_offline_tips(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", "test-key")

    def busy(prompt, key, models, used, **kw):
        used["skipped"] = [("a", "RuntimeError 503")]
        raise L.PlanUnavailable(RuntimeError("503"), used["skipped"])

    monkeypatch.setattr(L, "plan_with_fallback", busy)
    at = run()
    at.button[0].click().run()
    assert not at.exception
    assert any(TEXT["en"]["busy"] in w.value for w in at.warning)
    assert any("Why it helps" in m.value for m in at.markdown)


def test_unexpected_error_still_shows_tips(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", "test-key")

    def boom(*a, **kw):
        raise ValueError("boom")

    monkeypatch.setattr(L, "plan_with_fallback", boom)
    at = run()
    at.button[0].click().run()
    assert any("AI plan unavailable (ValueError)" in w.value for w in at.warning)
    assert any("Why it helps" in m.value for m in at.markdown)


def test_failed_air_quality_fetch_shows_error_and_no_numbers(monkeypatch):
    def down(lat, lon, timeout=10):
        raise ConnectionError("offline")

    monkeypatch.setattr(L, "fetch_aqi", down)
    at = AppTest.from_file(APP, default_timeout=30).run()
    assert any(TEXT["en"]["fail"] in e.value for e in at.error)
    assert len(at.metric) == 0


def test_long_commute_hides_the_co2_card():
    at = run()
    at.sidebar.selectbox(key="sample").set_value("Kolkata gig worker").run()
    assert not at.exception
    assert not any(TEXT["en"]["co2"] in label for label in labels(at))


def test_every_text_key_exists_in_both_languages():
    assert set(TEXT["en"]) == set(TEXT["hi"])
    for key in TEXT["en"]:
        assert type(TEXT["en"][key]) is type(TEXT["hi"][key]), key
        if isinstance(TEXT["en"][key], dict):
            assert set(TEXT["en"][key]) == set(TEXT["hi"][key]), key
    for profile in L.PROFILES.values():
        assert profile["household"] in TEXT["en"]["hh"]
        assert profile["mode"] in TEXT["en"]["modes"]
        assert profile["mask"] in TEXT["en"]["masks"]